#!/usr/bin/env python3
"""Check pinned Codex sources and embed their prompts for Maki's Lua loader."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "vendor/codex"
DESTINATION = ROOT / "lua/auto_approve/codex_prompts.lua"


def generated_module():
    manifest = json.loads((VENDOR / "source.json").read_text())
    sources = {}
    for name, entry in manifest["files"].items():
        data = (VENDOR / name).read_bytes()
        blob = hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()
        if blob != entry["git_blob"]:
            raise ValueError(f"{name} differs from pinned upstream blob {entry['git_blob']}")
        sources[name] = data.decode("utf-8")
    output = re.search(r'pub fn guardian_output_contract_prompt\(\).*?r#"(.*?)"#',
                       sources["assessment.rs"], re.S)
    if output is None:
        raise ValueError("Cannot locate Codex's output contract")
    prompts = {"template": sources["policy_template.md"], "policy": sources["policy.md"],
               "output_contract": output.group(1)}
    result = "-- Generated by scripts/codex-prompts.py; edit the pinned sources, not this file.\n"
    result += "-- OpenAI Codex (Apache-2.0), revision " + manifest["revision"] + ". See NOTICE.\n"
    result += "local M = {}\n"
    for name, value in prompts.items():
        if "]====]" in value:
            raise ValueError("Prompt contains the Lua string delimiter")
        result += "M." + name + " = [====[\n" + value + "]====]\n"
    return result + "return M\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the Lua prompt module")
    args = parser.parse_args()
    expected = generated_module()
    if args.write:
        DESTINATION.write_text(expected, encoding="utf-8")
    elif not DESTINATION.exists() or DESTINATION.read_text(encoding="utf-8") != expected:
        parser.error("Bundled prompts differ; run python3 scripts/codex-prompts.py --write")
    print("Pinned Codex prompt sources and Lua bundle match.")
